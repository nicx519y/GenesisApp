import 'dart:ui';

import 'app_localizations.dart';

/// Provides localized copy to presentation helpers that cannot receive a
/// [BuildContext]. Widgets should prefer `context.l10n`.
abstract final class GenesisL10n {
  static AppLocalizations? _current;

  static AppLocalizations get current =>
      _current ?? _lookup(PlatformDispatcher.instance.locale);

  static void bind(AppLocalizations localizations) {
    _current = localizations;
  }

  static AppLocalizations _lookup(Locale locale) {
    return lookupAppLocalizations(
      resolveGenesisSupportedLocale(locale, AppLocalizations.supportedLocales),
    );
  }
}

/// Resolves a platform locale to one of the exact locales generated by Flutter.
/// A language-only match is not safe to pass to [lookupAppLocalizations] when
/// the app contains only a regional variant such as zh_TW.
Locale resolveGenesisSupportedLocale(
  Locale locale,
  List<Locale> supportedLocales,
) {
  for (final candidate in supportedLocales) {
    if (candidate == locale) return candidate;
  }
  for (final candidate in supportedLocales) {
    if (candidate.languageCode == locale.languageCode &&
        candidate.scriptCode == locale.scriptCode) {
      return candidate;
    }
  }
  for (final candidate in supportedLocales) {
    if (candidate.languageCode == locale.languageCode) return candidate;
  }
  return supportedLocales.firstWhere(
    (candidate) => candidate.languageCode == 'en',
    orElse: () => supportedLocales.first,
  );
}
