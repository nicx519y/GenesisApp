typedef QaContractHook = Future<Object?> Function(Map<String, dynamic>, bool, bool);
final _qaContractHooks = <String, ({QaContractHook handler, String phase, String kind})>{};
final _qaObserverFailures = <String, Object>{};
DebugPrintCallback? _qaOriginalDebugPrint;
/// Generic QA registrations; implementations remain in owned QA modules.
void registerQaHook(String id, QaContractHook handler, [String phase = 'after_start']) {
  final kind = id.split('.').first;
  if (!['contract', 'observe', 'log', 'fixture'].contains(kind) || id.length <= kind.length + 1 ||
      !['before_start', 'after_start', 'any'].contains(phase)) {
    throw ArgumentError('Invalid QA namespace or lifecycle phase');
  }
  if (_qaContractHooks.containsKey(id)) throw StateError('Duplicate QA hook');
  _qaContractHooks[id] = (handler: handler, phase: phase, kind: kind);
}
/// Forward the existing debug output unchanged; QA observer failures cannot affect business code.
void installQaLogObservation() {
  if (_qaOriginalDebugPrint != null) return;
  _qaOriginalDebugPrint = debugPrint;
  debugPrint = _forwardQaDebugLog;
}
void _forwardQaDebugLog(String? message, {int? wrapWidth}) {
  _qaOriginalDebugPrint?.call(message, wrapWidth: wrapWidth);
  final bridge = QaBridge.current;
  if (bridge == null) return;
  for (final entry in _qaContractHooks.entries.where((entry) => entry.value.kind == 'log')) {
    if ((entry.value.phase == 'before_start' && bridge.started) ||
        (entry.value.phase == 'after_start' && !bridge.started)) { continue; }
    try {
      entry.value.handler({'message': message}, bridge._prepared, bridge.started)
          .catchError((Object error) { _qaObserverFailures[entry.key] = error; return null; });
    } catch (error) { _qaObserverFailures[entry.key] = error; }
  }
}
void _restoreQaLogObservation() {
  if (_qaOriginalDebugPrint != null && identical(debugPrint, _forwardQaDebugLog)) {
    debugPrint = _qaOriginalDebugPrint!;
  }
  _qaOriginalDebugPrint = null;
  _qaObserverFailures.clear();
}
